"""Publish a run report on ``main``, documentation only (AGENTS §16; the mechanism of CO.RA.PAN's
``scripts/publish_run_report_v1.py``, adapted).

    python scripts/publish_run_report.py publish docs/agent-runs/<YYYY-MM-DD_title>.md --status PARTIAL [--ref <branch|commit>] [--update]
    python scripts/publish_run_report.py check [--ref <branch|commit>]

A publication is **one commit on main** whose tree is main's tree plus exactly two paths: the report, with the bytes it
has *as committed* at ``--ref`` (default: the current branch), and its row in the generated
``docs/agent-runs/INDEX.md``. Nothing else of the source branch enters, and the commit is not a merge. It is made with
git plumbing on a temporary index, so neither the source worktree nor the main checkout is switched, and main's ref is
moved by compare-and-swap: if main moved meanwhile, nothing is published. Afterwards the two files are written into the
main checkout and staged, so that its index matches its HEAD.

Refusals (exit 1, ``REFUSED: …``), each before anything is written:

* a path that is not ``docs/agent-runs/<YYYY-MM-DD_title>.md``; a report not committed at ``--ref``;
* ``--status`` other than the report's own ``Status:`` line, or a report without ``EXTERNAL_API_USAGE = …`` (AGENTS §7);
* the main checkout not on ``main``; the report or ``INDEX.md`` changed, staged or untracked there with other bytes;
* a report already on main with other bytes, unless ``--update`` (a later state of *the same* run's report).

Publishing the same bytes again changes nothing (``NO_CHANGE``). Pushing ``main`` is not part of this tool: a
publication, a commit, a merge and a push are separate acts (AGENTS §16). ``check`` lists the reports of ``--ref``
that are missing on main or differ from it (exit 2 when there are any).
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
INDEX = "docs/agent-runs/INDEX.md"
REPORT = re.compile(r"^docs/agent-runs/\d{4}-\d{2}-\d{2}_[a-z0-9]+(?:-[a-z0-9]+)*\.md$")
STATUSES = ("IN_PROGRESS", "PASS", "PARTIAL", "FAIL", "BLOCKED")
STATUS_LINE = re.compile(r"Status:\**\s*`?(" + "|".join(STATUSES) + r")\b")
API_STATEMENT = re.compile(r"EXTERNAL_API_USAGE = [A-Z_]+")
TRAILER = "Published-By: publish_run_report"
BEGIN, END = "<!-- runs:begin -->", "<!-- runs:end -->"
INDEX_HEAD = (
    "# Run reports on main\n\n"
    "Generated by `scripts/publish_run_report.py`; do not edit the table by hand. One row per published run report;\n"
    "\"Source\" is the branch and commit the published bytes were taken from. A row says the report is on `main`; it says\n"
    "nothing about whether the run's code is merged (see the report itself).\n\n"
    "| Report | Title | Status | Source (branch @ commit) | Published (UTC) |\n|---|---|---|---|---|\n"
)


class PublishError(RuntimeError):
    pass


def git(*args: str, cwd: Path, env: dict | None = None, data: bytes | None = None) -> str:
    result = subprocess.run(["git", *args], cwd=cwd, input=data, capture_output=True, env=env)
    if result.returncode:
        raise PublishError(f"git {' '.join(args)}: {result.stderr.decode('utf-8', 'replace').strip()}")
    return result.stdout.decode("utf-8")


def main_checkout(repo: Path) -> Path:
    path = None
    for line in git("worktree", "list", "--porcelain", cwd=repo).splitlines():
        if line.startswith("worktree "):
            path = Path(line[len("worktree "):])
        elif line == "branch refs/heads/main" and path is not None:
            return path
    raise PublishError("no worktree has main checked out")


def blob_at(commit: str, path: str, cwd: Path) -> bytes | None:
    result = subprocess.run(["git", "cat-file", "-p", f"{commit}:{path}"], cwd=cwd, capture_output=True)
    return result.stdout if result.returncode == 0 else None


def title_of(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip().replace("|", "/")[:160]
    return "(no title)"


def render_index(existing: str | None, rows: dict[str, str]) -> bytes:
    current = {}
    if existing and BEGIN in existing and END in existing:
        for line in existing.split(BEGIN, 1)[1].split(END, 1)[0].splitlines():
            match = re.match(r"^\| \[([^\]]+)\]", line)
            if match:
                current[match.group(1)] = line
    current.update(rows)
    body = "\n".join(current[name] for name in sorted(current, reverse=True))
    return (INDEX_HEAD + BEGIN + "\n" + body + "\n" + END + "\n").encode("utf-8")


def _guard(checkout: Path, path: str, new: bytes) -> None:
    """Refuse when the main checkout holds someone's change at ``path``: staged, modified, or untracked with other bytes."""
    state = git("status", "--porcelain=v1", "--untracked-files=all", "--", path, cwd=checkout)
    if not state.strip():
        return
    on_disk = checkout / path
    if state.startswith("??") and on_disk.is_file() and on_disk.read_bytes() == new:
        return
    raise PublishError(f"the main checkout holds a change at {path} that is not this publication: {state.strip()}")


def commit_on_main(checkout: Path, old: str, files: dict[str, bytes], message: str) -> str:
    """One commit on main = ``old``'s tree plus ``files``, moved by compare-and-swap from ``old``; then the checkout synced."""
    env = dict(os.environ)
    with tempfile.TemporaryDirectory() as scratch:
        env["GIT_INDEX_FILE"] = str(Path(scratch) / "index")
        git("read-tree", old, cwd=checkout, env=env)
        for path, data in files.items():
            blob = git("hash-object", "-w", "--stdin", f"--path={path}", cwd=checkout, data=data).strip()
            git("update-index", "--add", "--cacheinfo", f"100644,{blob},{path}", cwd=checkout, env=env)
        tree = git("write-tree", cwd=checkout, env=env).strip()
    new = git("commit-tree", tree, "-p", old, "-m", message, cwd=checkout).strip()
    git("update-ref", "-m", "publish_run_report", "refs/heads/main", new, old, cwd=checkout)
    try:
        for path, data in files.items():
            target = checkout / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        git("add", "--", *files, cwd=checkout)
    except (OSError, PublishError) as error:
        raise PublishError(f"PUBLISHED as {new}, but the main checkout is not in step ({error}); there run: "
                           f"git checkout HEAD -- {' '.join(files)}") from error
    return new


def publish(path: str, status: str, *, ref: str | None = None, update: bool = False, repo: Path = REPO,
            now: datetime | None = None) -> dict:
    path = path.replace("\\", "/")
    if not REPORT.match(path):
        raise PublishError(f"not a run report path: {path}")
    if status not in STATUSES:
        raise PublishError(f"status {status!r} is not one of {', '.join(STATUSES)}")
    source = git("rev-parse", "--verify", f"{ref or 'HEAD'}^{{commit}}", cwd=repo).strip()
    branch = ref or git("rev-parse", "--abbrev-ref", "HEAD", cwd=repo).strip()
    data = blob_at(source, path, repo)
    if data is None:
        raise PublishError(f"{path} is not committed at {branch} ({source[:9]})")
    text = data.decode("utf-8")
    declared = STATUS_LINE.search(text)
    if declared is None or declared.group(1) != status:
        raise PublishError(f"--status {status} but the report says {declared.group(1) if declared else 'no Status: line'}")
    if not API_STATEMENT.search(text):
        raise PublishError("the report has no EXTERNAL_API_USAGE statement (AGENTS §7)")
    checkout = main_checkout(repo)
    if git("symbolic-ref", "-q", "HEAD", cwd=checkout).strip() != "refs/heads/main":
        raise PublishError("the main checkout is not on main")
    old = git("rev-parse", "HEAD", cwd=checkout).strip()
    published = blob_at(old, path, checkout)
    if published is not None and published != data and not update:
        raise PublishError(f"{path} is on main with other bytes; --update replaces a publication of the same run's report")
    name = path.rsplit("/", 1)[1]
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y-%m-%d %H:%M")
    row = f"| [{name}]({name}) | {title_of(text)} | {status} | `{branch}` @ `{source[:9]}` | {stamp} |"
    existing_index = blob_at(old, INDEX, checkout)
    if published == data and existing_index is not None and row.rsplit(" | ", 1)[0] in existing_index.decode("utf-8"):
        return {"result": "NO_CHANGE", "main": old, "report": path}
    index = render_index(existing_index.decode("utf-8") if existing_index else None, {name: row})
    files = {path: data, INDEX: index}
    for target, content in files.items():
        _guard(checkout, target, content)
    message = (f"Run reports published (docs only): {name}\n\nSource {branch} @ {source}; status {status}. "
               f"No code of the source branch is part of this commit.\n\n{TRAILER}\n")
    new = commit_on_main(checkout, old, files, message)
    return {"result": "PUBLISHED", "main": new, "previous_main": old, "report": path, "source": source}


def check(ref: str | None = None, *, repo: Path = REPO) -> list[str]:
    source = git("rev-parse", "--verify", f"{ref or 'HEAD'}^{{commit}}", cwd=repo).strip()
    drift = []
    for line in git("diff", "--name-status", "main", source, "--", "docs/agent-runs/", cwd=repo).splitlines():
        state, path = line.split("\t", 1)
        if REPORT.match(path) and state in ("A", "M"):
            drift.append(f"{'MISSING_ON_MAIN' if state == 'A' else 'DIFFERS_FROM_MAIN'} {path}")
    return drift


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    publish_cmd = commands.add_parser("publish")
    publish_cmd.add_argument("report")
    publish_cmd.add_argument("--status", required=True, choices=STATUSES)
    publish_cmd.add_argument("--ref")
    publish_cmd.add_argument("--update", action="store_true")
    check_cmd = commands.add_parser("check")
    check_cmd.add_argument("--ref")
    arguments = parser.parse_args(argv)
    try:
        if arguments.command == "publish":
            result = publish(arguments.report, arguments.status, ref=arguments.ref, update=arguments.update)
            print(" ".join(f"{key}={value}" for key, value in result.items()))
            return 0
        drift = check(arguments.ref)
        print("\n".join(drift) or "no drift")
        return 2 if drift else 0
    except PublishError as error:
        print(f"REFUSED: {error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
