"""Declared production provenance of a press text (CPD-0039): AI use (``ai-disclosure/1``) and news-agency credit
(``agency-credit/1``). Both are *publisher statements read by a rule*, recorded with the statement, its place and its scope.

**Provenance is documented, it is not a quality judgement.** An AI-made or an agency text is wanted corpus material; nothing
here admits or rejects anything (``content_quality`` does not read these layers).

**Unknown is not negative.** A page without an AI disclosure is ``unknown`` (no disclosure observed), never "made without
AI"; a page without an agency credit is ``unknown``, never "own reporting".

AI disclosure -- what counts as a statement:

* a block that *begins* with a disclosure form (optionally after ``*``, ``Nota:``, ``Aviso:``, an opening bracket): a subject
  (``este artículo`` / ``contenido`` / ``resumen`` / ``audio`` / ``imagen`` …) and a production verb with AI as its means;
  or a caption that says its image was generated with AI. A text that merely *mentions* artificial intelligence -- a news
  story about AI, a quoted sentence -- has no such form and never yields a label;
* at most ``MAX_STATEMENT_CHARACTERS`` long (a disclosure is a note, not a paragraph of reporting);
* a statement that the same outlet prints identically on most of its pages is a site-wide notice, not a statement about this
  article (``site_wide_statements``; corpus-level, computed per outlet).

Values for the article's own text (``value``): ``generated`` (the text was generated by AI -- a human review may be stated
beside it), ``assisted`` (written with the help or collaboration of AI, or partly drafted with it), ``translated`` (translated
into Spanish with AI), ``unclear`` (an AI production note without a subject). Components beside the article -- a machine
summary, a synthetic audio version, an AI image -- are listed in ``components`` and never stand for the article text.

Agency credit -- positions read, and only these: the article's JSON-LD ``author`` / ``creator``; the ``author`` meta tags; the
JSON-LD ``sourceOrganization`` / ``copyrightHolder`` / ``provider`` / ``creditText`` / ``dateline``; the opening of the first body
block (a wire dateline, ``Madrid, 10 oct (EFE).-``); a byline block that begins with ``Por`` / ``Redacción``; and a credit note
(``Con información de EFE``). A photo credit (``Foto: AFP``, a caption ending in ``(EFE)``) credits a picture, not the text,
and an agency quoted in the running text (``según informó la agencia EFE``) is a source, not the author: neither is read.
``agency_use``: ``edited_declared`` (the page says its text was written with the agency's material), ``joint_credit`` (agency
and newsroom or a person credited together), ``credit_only`` (the agency is credited; how its text was taken over is not
stated). ``verbatim_declared`` is in the vocabulary for a page that says it reproduces the wire text unchanged; no stored page
says so, so no rule assigns it. Whether two outlets published the same text is a different kind of evidence
(``coprepan.text_reuse``) and is never inferred from a credit.
"""

from __future__ import annotations

import re
import unicodedata
from collections import Counter, defaultdict
from typing import Any, Iterable, Mapping

from . import extraction as E
from .editorial_metadata import KNOWN, UNKNOWN, layer

LAYER_AI, LAYER_AGENCY = "ai-disclosure/1", "agency-credit/1"
MAX_STATEMENT_CHARACTERS = 400
SITE_WIDE_SHARE, SITE_WIDE_MIN_PAGES = 0.8, 10
AI_VALUES = ("generated", "assisted", "translated", "unclear")
AI_COMPONENTS = ("summary", "audio", "image")
AGENCY_USES = ("verbatim_declared", "edited_declared", "joint_credit", "credit_only")

_AI = r"(?:la\s+|una\s+)?(?:inteligencia\s+artificial(?:\s+generativa)?|\bIA\b(?:\s+generativa)?|\bAI\b|ChatGPT|Gemini|Copilot|Claude)"
_TOOL = r"(?:(?:una|la|el|un)\s+)?(?:herramientas?|sistema|modelo|asistente|tecnolog[ií]a)s?\s+(?:propi[oa]\s+)?(?:de|basad[oa]s?\s+en)\s+"
_LEAD = r"^\s*(?:\*+\s*|nota\s*:\s*|aviso\s*:\s*|\(\s*)?"
_SUBJECT_TEXT = r"(?:(?:est[ea]s?|el|la|esta)\s+)?(?:art[ií]culo|nota|texto|contenido|noticia|informaci[oó]n|historia|publicaci[oó]n|reportaje|cr[oó]nica)"
_ASSIST = r"(?:con\s+(?:la\s+)?(?:ayuda|asistencia|apoyo|colaboraci[oó]n)\s+de|asistid[oa]\s+por|(?:mediante|en)\s+(?:la\s+)?colaboraci[oó]n)"
# the forms, in the order they are tried; each: (form id, value or component, pattern)
AI_FORMS: tuple[tuple[str, str, re.Pattern[str]], ...] = tuple((form, value, re.compile(pattern, re.I)) for form, value, pattern in (
    ("text_translated", "translated",
     _LEAD + _SUBJECT_TEXT + r"\s+(?:fue|ha\s+sido|es)\s+(?:\w+\s+){0,6}?traducid[oa]\b.{0,120}?(?:con|mediante|por)\s+(?:" + _TOOL + r")?" + _AI),
    ("text_translated", "translated",
     _LEAD + _SUBJECT_TEXT + r".{0,120}?(?:usamos|utilizamos|se\s+us[oó]|se\s+utiliz[oó])\s+(?:" + _TOOL + r")" + _AI + r".{0,40}?tradu"),
    ("text_assisted", "assisted",
     _LEAD + _SUBJECT_TEXT + r"\s+(?:fue|ha\s+sido|es)\s+(?:\w+\s+){0,3}?(?:cread|elaborad|producid|redactad|escrit|generad|realizad|hech)[oa]\s+"
     r".{0,80}?" + _ASSIST + r".{0,80}?" + _AI),
    ("text_assisted", "assisted",
     _LEAD + _SUBJECT_TEXT + r"\s+incluye\s+(?:redacci[oó]n|texto|contenido|partes?)\s+(?:\w+\s+){0,3}?(?:con|mediante|por)\s+(?:" + _TOOL + r")?" + _AI),
    ("text_generated", "generated",
     _LEAD + _SUBJECT_TEXT + r"\s+(?:(?:fue|ha\s+sido|es)\s+)?(?:\w+\s+){0,2}?(?:generad|cread|redactad|escrit|elaborad|producid)[oa]\s+"
     r"(?:(?:íntegra|completa|total|automática)mente\s+)?(?:por|con|mediante)\s+(?:" + _TOOL + r")?" + _AI),
    ("summary", "summary",
     _LEAD + r"(?:est[eo]s?\s+)?res[uú]men(?:es)?\s+(?:\w+\s+){0,2}?(?:fue|fueron|ha\s+sido|son|es)?\s*(?:generad|cread|elaborad|producid)[oa]s?\s+"
     r"(?:autom[aá]ticamente\s+)?(?:por|con|mediante)\s+(?:" + _TOOL + r")?" + _AI),
    ("summary", "summary", _LEAD + r"res[uú]men\s+(?:generado|creado|elaborado)\s+(?:con|por)\s+(?:" + _TOOL + r")?" + _AI),
    ("audio", "audio",
     _LEAD + r"(?:escucha\s+esta\s+nota\s+)?(?:el\s+)?audio\b.{0,60}?(?:generad[oa]|cread[oa]|voz\s+sint[eé]tica\s+generada)\s+(?:por|con)\s+(?:" + _TOOL + r")?" + _AI),
    ("image", "image", r"(?:^|foto\s*:\s*|\(\s*)(?:imagen|ilustraci[oó]n|fotomontaje|foto)\s+(?:\w+\s+){0,4}?(?:generad|cread|editad|trabajad|hech)[oa]\s+"
     r"(?:\w+\s+){0,3}?(?:con|por|mediante)\s+" + _AI),
    ("image_caption", "image", r"(?:imagen|ilustraci[oó]n|fotomontaje)\s+(?:\w+\s+){0,4}?(?:generad|cread|editad|trabajad|hech)[oa]\s+"
     r"(?:\w+\s+){0,3}?(?:con|por|mediante)\s+" + _AI + r"[^.]{0,40}\.?\s*$"),     # the credit that closes a caption
    ("unclear", "unclear", r"^\s*\(?\s*generad[oa]\s+(?:con|por)\s+" + _AI + r"\s*\)?\s*\.?\s*$"),
))
_HUMAN_REVIEW = re.compile(r"(?:(?:revisad|supervisad|verificad|curad|chequead|editad)[oa]s?\s+(?:y\s+\w+\s+)?por\s+(?:un|una|el|la|nuestr[oa]s?|los|las)?\s*"
                           r"(?:\w+\s+)?(?:periodista|editor|editora|equipo|redacci[oó]n|autor|autora|personal|profesional)|"
                           r"(?:periodista|editor|editora)\b.{0,40}?\brevis[oó]|^\s*supervisad[oa]\b|\.\s*supervisad[oa]\b|"
                           r"(?:bajo\s+)?(?:supervisi[oó]n|edici[oó]n|revisi[oó]n|curadur[ií]a)\s+(?:y\s+(?:edici[oó]n|revisi[oó]n)\s+)?human[oa])", re.I)
_TOOLS = re.compile(r"\b(ChatGPT|GPT-?\d[\w.]*|OpenAI|Gemini|Google|Claude|Anthropic|Copilot|Microsoft|Llama|Meta AI|Grok|DeepL|ElevenLabs)\b")
_PREFIX_TITLE_UNCLEAR = re.compile(r"\(\s*generad[oa]\s+(?:con|por)\s+(?:la\s+)?(?:inteligencia\s+artificial|IA)\s*\)\s*$", re.I)


def _fold(text: str) -> str:
    return unicodedata.normalize("NFC", re.sub(r"\s+", " ", text)).strip().lower()


def ai_statements(record: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Every AI production statement of an extraction record, with its place and form."""
    out = []
    blocks = record.get("blocks", [])
    for block in blocks:
        text = block["text"]
        if block["kind"] == "title" and _PREFIX_TITLE_UNCLEAR.search(text):
            out.append(_statement(block, "unclear", "title_suffix", text))
            continue
        if len(text) > MAX_STATEMENT_CHARACTERS and block["kind"] != "caption":
            continue
        for form, value, pattern in AI_FORMS:
            if form == "image" and not (block["kind"] == "caption" or len(text) <= 300):
                continue
            if form == "image_caption" and not (block["kind"] == "caption" or (block["role"] == E.ROLE_NON_BODY and block["kind"] != "heading")):
                continue          # only where a picture is described: never in running text, never a headline about AI images
            if pattern.search(text):
                out.append(_statement(block, value, form, text))
                break
    return out


def _statement(block: Mapping[str, Any], value: str, form: str, text: str) -> dict[str, Any]:
    tool = sorted(set(_TOOLS.findall(text)))
    scope = "article" if value in AI_VALUES else value
    return {"value": value, "form": form, "scope": scope, "text": text[:MAX_STATEMENT_CHARACTERS], "block_index": block["index"],
            "block_role": block["role"], "block_kind": block["kind"], "module": block.get("module"),
            "human_review_stated": bool(_HUMAN_REVIEW.search(text)), "tools_named": tool}


def site_wide_statements(pages: Iterable[Mapping[str, Any]]) -> dict[str, set[str]]:
    """Per outlet, the AI statements printed on at least ``SITE_WIDE_SHARE`` of its pages (at least ``SITE_WIDE_MIN_PAGES``
    pages): a site notice, not a statement about any one article. ``pages``: ``{"outlet_id", "statements"}``."""
    counts, totals = defaultdict(Counter), Counter()
    for page in pages:
        totals[page["outlet_id"]] += 1
        # only statements about the article's text: a machine summary or audio module the outlet attaches to most of its
        # pages is a component of each of those pages, not a site notice
        for text in {_fold(s["text"]) for s in page["statements"] if s["value"] in AI_VALUES}:
            counts[page["outlet_id"]][text] += 1
    return {outlet: {text for text, n in counter.items() if totals[outlet] >= SITE_WIDE_MIN_PAGES and n >= SITE_WIDE_SHARE * totals[outlet]}
            for outlet, counter in counts.items()}


def ai_disclosure(record: Mapping[str, Any], *, site_wide: set[str] = frozenset()) -> dict[str, Any]:
    """``ai-disclosure/1`` for one extraction record."""
    rule = {"rule": LAYER_AI, "max_statement_characters": MAX_STATEMENT_CHARACTERS}
    statements = ai_statements(record)
    kept = [s for s in statements if _fold(s["text"]) not in site_wide]
    dropped = [s for s in statements if _fold(s["text"]) in site_wide]
    components = sorted({s["value"] for s in kept if s["value"] in AI_COMPONENTS})
    article = [s for s in kept if s["value"] in AI_VALUES]
    attributes = {"components": components, "statements": kept, "site_wide_statements_ignored": dropped}
    if not article:
        reason = "site_wide_statement_only" if dropped and not kept else ("components_only" if components else "no_disclosure_observed")
        return layer(LAYER_AI, None, UNKNOWN, basis=[], rule=rule, reason=reason, attributes=attributes)
    # the most specific statement about the article's text decides; several different ones are all kept
    order = ("generated", "translated", "assisted", "unclear")
    values = sorted({s["value"] for s in article}, key=order.index)
    attributes["all_values"] = values
    return layer(LAYER_AI, values[0], KNOWN, basis=[{"basis": f"block_{s['block_role']}", "block_index": s["block_index"],
                                                     "form": s["form"]} for s in article], rule=rule, attributes=attributes)


